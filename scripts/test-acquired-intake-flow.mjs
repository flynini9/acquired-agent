import assert from 'node:assert/strict';
import {identitiesReady,nextIdentity,remapSeedPins} from '../lib/acquired/intake-flow.ts';
const queen={id:'queen',name:'Queen',type:'artist'},hamilton={id:'hamilton',name:'Hamilton',type:'artist'},frozen={id:'frozen',name:'Frozen',type:'movie',year:2013};
const pins={seedPinned:{}};
assert.deepEqual(nextIdentity(' Queen ',' Hamilton\n\nFrozen ',pins),{field:'destination',query:'Queen'});
pins.destPinned=queen;
assert.deepEqual(nextIdentity('Queen','Hamilton\nFrozen',pins),{field:'seed',query:'Hamilton',index:0});
pins.seedPinned[0]=hamilton;
assert.equal(identitiesReady('Queen','Hamilton\nFrozen',pins),false,'Review/build must wait for every seed, not just the destination.');
assert.deepEqual(nextIdentity('Queen','Hamilton\nFrozen',pins),{field:'seed',query:'Frozen',index:1});
pins.seedPinned[1]=frozen;
assert.equal(identitiesReady('Queen','Hamilton\nFrozen',pins),true);
assert.equal(identitiesReady('Queen','\n ',pins),false);
assert.equal(identitiesReady('','Hamilton',pins),false);
const reordered=remapSeedPins('Hamilton\nFrozen','Frozen\nHamilton',pins.seedPinned);
assert.deepEqual(reordered,{0:frozen,1:hamilton},'Reordering must keep the confirmed identities attached to their names.');
const edited=remapSeedPins('Hamilton\nFrozen','Hamilton\nOasis',pins.seedPinned);
assert.deepEqual(edited,{0:hamilton});
assert.deepEqual(nextIdentity('Queen','Hamilton\nOasis',{destPinned:queen,seedPinned:edited}),{field:'seed',query:'Oasis',index:1});
assert.deepEqual(remapSeedPins('Hamilton\nFrozen','\n Frozen \n',pins.seedPinned),{0:frozen});
assert.deepEqual(remapSeedPins('Hamilton','Hamilton\nHamilton',{0:hamilton}),{0:hamilton},'An added duplicate still needs its own explicit confirmation.');
console.log('Intake flow checks passed: both-end completion gate, sequential matching, blank inputs, reorder/delete/edit invalidation and duplicate-name confirmation. No live requests.');
