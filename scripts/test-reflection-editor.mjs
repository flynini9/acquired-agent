import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import ts from 'typescript';
const require=createRequire(import.meta.url),module={exports:{}};
const source=readFileSync(new URL('../app/acquired/reflection-editor.tsx',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}}).outputText;
new Function('require','module','exports',code)(require,module,module.exports);
let changed;
const editor=module.exports.ReflectionEditor({value:'Previous thought',disabled:false,onChange:value=>changed=value});
const field=editor.props.children.find(x=>x?.type==='textarea');
assert.equal(field.props.value,'Previous thought');
assert.equal(field.props.disabled,false);
field.props.onChange({target:{value:'A little more curious.'}});
assert.equal(changed,'A little more curious.');
const locked=module.exports.ReflectionEditor({value:'',disabled:true,onChange:()=>{}});
assert.equal(locked.props.children.find(x=>x?.type==='textarea').props.disabled,true);
const page=readFileSync(new URL('../app/acquired/page.tsx',import.meta.url),'utf8');
assert.ok(page.includes('<ReflectionEditor disabled={!!busy||syncBlocked.current}'));
assert.ok(page.includes('onChange={value=>void persist({...walkRef.current!,reflection:value})}'));
assert.ok(page.includes('<aside className="reflection-tools"'));
assert.ok(page.includes('<section className="after-taste"'));
assert.ok(!page.includes('<details className="after-taste"'));
const more=page.slice(page.indexOf('<section className="after-taste"'),page.indexOf('</aside>',page.indexOf('<section className="after-taste"')));
assert.ok(more.includes('<Links items={[item]}/>'));
assert.ok(!more.includes('<Rating')&&!more.includes('onRate=')&&!more.includes('rating-options'));
assert.ok(page.indexOf('className="reflection-actions"')<page.indexOf('<aside className="reflection-tools"'));
assert.ok(page.includes('ss.cont!=null?"✓ Visited":"Not visited"'));
assert.ok(page.includes('<div className="reflection-overview">{journeyProgress}'));
console.log('14 reflection editor and completion presentation checks passed; no live requests.');
